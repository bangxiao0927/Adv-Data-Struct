public class Food {
// Food Class
// Instance Variables
// 	- name : String - Food name.
// Constructor
// 	+ Food(String) - Sets up the instance variable accordingly.
// Methods
// 	+ toString() : String - Return the name.

    private String name;

    public Food(String name) {
        this.name = name;
    }

    public String toString() {
        return name;
    }
}
